package dev.schlubbe.musicagent.podcast

import android.util.Log
import dev.schlubbe.musicagent.data.extract.di.ExtractionHttpClient
import dev.schlubbe.musicagent.data.remote.dto.TrackResultDto
import dev.schlubbe.musicagent.data.repository.LyricLine
import dev.schlubbe.musicagent.data.repository.Lyrics
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import okhttp3.OkHttpClient
import okhttp3.Request
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import javax.inject.Inject
import javax.inject.Singleton

/**
 * The text to read along with a spoken episode, shown where a song shows its lyrics:
 * - a YouTube video: its subtitles (the uploader's own, else YouTube's automatic ones),
 *   with real timestamps;
 * - a LibriVox audiobook: the book it was read from (Project Gutenberg, Projekt
 *   Gutenberg-DE or Wikisource, as LibriVox links it). The text has no timestamps, so
 *   each chapter's share of the book is estimated from its share of the total running
 *   time and the lines inside it from their position: close, but not exact.
 * Other episodes (ARD, podcasts) have no free text, so they get none.
 */
@Singleton
class SpokenText @Inject constructor(
    @ExtractionHttpClient private val http: OkHttpClient,
    private val podcasts: PodcastRepository,
) {
    private val cache = object : LinkedHashMap<String, Lyrics?>(16, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, Lyrics?>?) = size > 30
    }
    private val books = object : LinkedHashMap<String, String?>(4, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, String?>?) = size > 3
    }
    private val mutex = Mutex()

    /** The text for [track] (a `podcast` track), or null when there is none. */
    suspend fun textFor(track: TrackResultDto): Lyrics? = withContext(Dispatchers.IO) {
        val key = track.sourceId
        mutex.withLock { if (cache.containsKey(key)) return@withContext cache[key] }
        val text = runCatching {
            when {
                isYouTubeEpisode(track.source, track.sourceId) -> youTubeSubtitles(track.sourceId)
                track.album?.let(::libriVoxId) != null -> libriVox(track)
                else -> null
            }
        }.onFailure { Log.w(TAG, "no text for ${track.title}", it) }.getOrNull()
        mutex.withLock { cache[key] = text }
        text
    }

    private fun youTubeSubtitles(url: String): Lyrics? {
        val info = StreamInfo.getInfo(ServiceList.YouTube, url)
        val pick = pickSubtitles(info.subtitles) ?: return null
        val body = get(srv1Url(pick.content)) ?: return null
        val lines = parseSrv1(body).takeIf { it.isNotEmpty() } ?: return null
        return Lyrics(
            synced = lines,
            plain = null,
            credit = if (pick.isAutoGenerated) "Automatische Untertitel von YouTube" else "Untertitel von YouTube",
        )
    }

    private suspend fun libriVox(track: TrackResultDto): Lyrics? {
        val showId = track.album ?: return null
        val bookId = libriVoxId(showId) ?: return null
        val show = podcasts.loadShow(showId)
        val episodes = show.episodes
        val index = episodes.indexOfFirst { it.audioUrl == track.sourceId }.takeIf { it >= 0 } ?: return null
        val book = bookText(bookId, episodes.size) ?: return null
        // the chapter's share of the book = its share of the running time
        val seconds = episodes.map { (it.durationSec ?: 0).coerceAtLeast(0).toDouble() }
        val total = seconds.sum()
        val (from, to) = if (total > 0 && seconds.all { it > 0 }) {
            seconds.take(index).sum() / total to seconds.take(index + 1).sum() / total
        } else {
            index.toDouble() / episodes.size to (index + 1).toDouble() / episodes.size
        }
        val durationMs = (track.durationSec ?: episodes[index].durationSec ?: 0) * 1000L
        val lines = estimateLines(book, from, to, durationMs).takeIf { it.isNotEmpty() } ?: return null
        return Lyrics(synced = lines, plain = null, credit = "Buchtext über LibriVox, Zeiten geschätzt")
    }

    private suspend fun bookText(bookId: String, sections: Int): String? {
        mutex.withLock { if (books.containsKey(bookId)) return books[bookId] }
        val meta = get("https://librivox.org/api/feed/audiobooks/?id=$bookId&format=json")
        val source = meta?.let { Regex(""""url_text_source"\s*:\s*"([^"]*)"""").find(it)?.groupValues?.get(1) }
            ?.replace("\\/", "/")?.trim()
        val text = source?.let { fetchBook(it, sections) }?.let(::cleanBook)?.takeIf { it.length > 200 }
        mutex.withLock { books[bookId] = text }
        return text
    }

    /** Only sources whose pages are the plain text itself; anything else is left out. */
    private fun fetchBook(url: String, sections: Int): String? {
        Regex("""gutenberg\.org/(?:etext|ebooks)/(\d+)""").find(url)?.groupValues?.get(1)?.let { n ->
            return get("https://www.gutenberg.org/cache/epub/$n/pg$n.txt")?.let(::gutenbergBody)
        }
        if ("projekt-gutenberg.org" in url) {
            val chapter = Regex("""chap(\d{3})\.html""").find(url)
            if (chapter == null || sections <= 1) return get(url)?.let(::htmlText)
            // a book in several sections: the linked chapter and the ones after it
            val base = url.substringBefore(chapter.value)
            val first = chapter.groupValues[1].toInt()
            return (first until first + MAX_CHAPTERS).asSequence()
                .map { n -> get(base + "chap%03d.html".format(n))?.let(::htmlText) }
                .takeWhile { it != null }
                .filterNotNull()
                .joinToString("\n\n")
                .takeIf { it.isNotBlank() }
        }
        Regex("""de\.wikisource\.org/wiki/(.+)""").find(url)?.groupValues?.get(1)?.let { page ->
            return get("https://de.wikisource.org/w/index.php?title=$page&action=render")?.let(::htmlText)
        }
        return null
    }

    private fun get(url: String): String? = runCatching {
        http.newCall(Request.Builder().url(url).build()).execute().use { r ->
            if (!r.isSuccessful) null else r.body.string()
        }
    }.getOrNull()

    companion object {
        private const val TAG = "SpokenText"
        private const val MAX_CHAPTERS = 120

        /** LibriVox announces itself at the start of every section ("Kapitel 3 von …,
         * dies ist eine LibriVox-Aufnahme …") and says goodbye at the end. */
        private const val INTRO_MS = 12_000L
        private const val OUTRO_MS = 8_000L

        /** "rss:https://librivox.org/rss/549" -> "549". */
        fun libriVoxId(showId: String): String? =
            Regex("""librivox\.org/rss/(\d+)""").find(showId)?.groupValues?.get(1)

        /** German first, the uploader's own before YouTube's automatic ones. */
        fun pickSubtitles(streams: List<SubtitlesStream>): SubtitlesStream? {
            fun german(s: SubtitlesStream) = s.languageTag.lowercase().startsWith("de")
            return streams.firstOrNull { german(it) && !it.isAutoGenerated }
                ?: streams.firstOrNull { german(it) }
                ?: streams.firstOrNull { !it.isAutoGenerated }
                ?: streams.firstOrNull()
        }

        /** The same subtitles as "srv1", whatever format NewPipe lists (often only TTML). */
        fun srv1Url(url: String): String =
            if (Regex("[?&]fmt=").containsMatchIn(url)) url.replace(Regex("([?&]fmt=)[^&]*"), "$1srv1") else "$url&fmt=srv1"

        /** YouTube's "srv1" timed text: `<text start="1.2" dur="3.4">Words</text>`. */
        fun parseSrv1(xml: String): List<LyricLine> =
            Regex("""<text start="([\d.]+)"[^>]*>(.*?)</text>""", RegexOption.DOT_MATCHES_ALL).findAll(xml)
                .mapNotNull { m ->
                    val text = unescape(unescape(m.groupValues[2])).replace(Regex("<[^>]*>"), "")
                        .replace(Regex("\\s+"), " ").trim()
                    if (text.isEmpty() || text.startsWith("[") && text.endsWith("]")) return@mapNotNull null // [Musik]
                    LyricLine((m.groupValues[1].toDouble() * 1000).toLong(), text)
                }
                .fold(ArrayList<LyricLine>()) { out, line ->
                    // automatic captions cut mid-sentence ("Komm, lassen wir …" / "warten."):
                    // a fragment of one or two words joins the line before it
                    val last = out.lastOrNull()
                    if (last != null && line.text.split(' ').size <= 2 && last.text.length < 80 && line.timeMs - last.timeMs < 4_000) {
                        out[out.size - 1] = last.copy(text = last.text + " " + line.text)
                    } else {
                        out += line
                    }
                    out
                }

        /** The part of [book] between the fractions [from] and [to], cut at paragraph
         * starts and split into short lines, each timed by where it sits in the part. */
        fun estimateLines(book: String, from: Double, to: Double, durationMs: Long): List<LyricLine> {
            val start = paragraphStart(book, (book.length * from).toInt())
            val end = if (to >= 0.999) book.length else paragraphStart(book, (book.length * to).toInt())
            if (end <= start) return emptyList()
            val part = book.substring(start, end).replace(Regex("\\s+"), " ")
            val speaking = (durationMs - INTRO_MS - OUTRO_MS).coerceAtLeast(0)
            val lines = ArrayList<LyricLine>()
            var offset = 0
            for (sentence in sentences(part)) {
                val at = (part.indexOf(sentence, offset).takeIf { it >= 0 } ?: offset).coerceAtMost(part.length)
                offset = at + sentence.length
                val time = if (durationMs > 0) INTRO_MS + speaking * at / part.length else 0L
                lines += LyricLine(time, sentence)
            }
            return lines
        }

        private fun paragraphStart(book: String, near: Int): Int {
            if (near <= 0) return 0
            val before = book.lastIndexOf("\n\n", near)
            val after = book.indexOf("\n\n", near)
            return listOf(before, after).filter { it >= 0 }.minByOrNull { kotlin.math.abs(it - near) }?.plus(2) ?: near
        }

        /** Sentences, long ones broken at a comma, so a line fits the screen. */
        private fun sentences(text: String): List<String> =
            text.replace(Regex("\\s+"), " ")
                .split(Regex("""(?<=[.!?…:;]["»«“”']?)\s+"""))
                .flatMap { s -> if (s.length <= 160) listOf(s) else s.split(Regex("""(?<=,)\s+""")) }
                .map { it.trim() }
                .filter { it.isNotEmpty() }

        /** Project Gutenberg's own header and licence cut off. */
        fun gutenbergBody(text: String): String {
            val start = Regex("""\*\*\* ?START OF[^\n]*\n""").find(text)?.range?.last?.plus(1) ?: 0
            val end = Regex("""\*\*\* ?END OF""").find(text, start)?.range?.first ?: text.length
            // "Produced by …" credits of the transcribers, not part of the book
            return text.substring(start, end).trimStart().replace(Regex("""^Produced by[\s\S]*?\n\s*\n"""), "")
        }

        fun htmlText(html: String): String =
            unescape(
                html.substringAfter("<body", html)
                    .replace(Regex("(?is)<(script|style|head)[^>]*>.*?</\\1>"), "")
                    .replace(Regex("(?i)<br\\s*/?>"), "\n")
                    .replace(Regex("(?i)</(p|div|h\\d|li)>"), "\n\n")
                    .replace(Regex("<[^>]*>"), ""),
            )

        /** Line ends unified, single line breaks inside a paragraph joined. */
        fun cleanBook(text: String): String =
            text.replace("\r\n", "\n")
                .replace(Regex("[ \\t]+\n"), "\n")
                .replace(Regex("\n{3,}"), "\n\n")
                .trim()

        private fun unescape(s: String) = s
            .replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
            .replace("&quot;", "\"").replace("&#39;", "'").replace("&apos;", "'").replace("&nbsp;", " ")
            .replace(Regex("&#(\\d+);")) { m -> m.groupValues[1].toIntOrNull()?.toChar()?.toString() ?: "" }
    }
}
